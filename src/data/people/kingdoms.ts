function king(row: KingRow, kingdom: 'יהודה' | 'ישראל'): Person {
  const [id, name, fullName, from, to, summary] = row;
  return person({
    id,
    name,
    fullName,
    disambiguation: `מלך ${kingdom}`,
    gender: name === 'עתליה' ? 'female' : 'male',
    roles: [name === 'עתליה' ? 'queen' : 'king'],
    titles: [`מלך ${kingdom}`],
    periodIds: kingdom === 'ישראל' ? ['mamlachot', 'galut-israel'] : ['mamlachot', 'churban'],
    span: { from, to, certainty: 'certain', label: `ממלכת ${kingdom}` },
    certainty: 'certain',
    bookIds:
      kingdom === 'יהודה'
        ? ['melachim-a', 'melachim-b', 'divrei-hayamim-b']
        : ['melachim-a', 'melachim-b'],
    tribe: kingdom === 'יהודה' ? 'יהודה' : undefined,
    sources: [src('melachim-b', 'א׳–כ״ה')],
    summary,
  });
}

